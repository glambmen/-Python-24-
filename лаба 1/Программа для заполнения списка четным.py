# Программа для заполнения списка четными числами

# Ввод имени списка
list_name = input("Введите имя списка: ")

# Проверка корректности ввода границ диапазона
try:
    start = int(input("Введите начало диапазона: "))
    end = int(input("Введите конец диапазона: "))

    # Проверка порядка диапазона
    if start > end:
        print("Ошибка: начало диапазона не может быть больше конца.")
    else:
        even_numbers = []

        # Заполнение списка четными числами
        for number in range(start, end + 1):
            if number % 2 == 0:
                even_numbers.append(number)

        # Вывод результата
        print("\nРезультат работы программы:")
        print(f"Имя списка: {list_name}")
        print(f"Список четных чисел: {even_numbers}")

except ValueError:
    print("Ошибка: необходимо вводить только целые числа.")